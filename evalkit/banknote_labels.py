# -*- coding: utf-8 -*-
"""
Ручная разметка патчей-кандидатов: банкноты или нет.

Кандидаты собраны детектором предметов на столе (app/desk.py) по всем 40
роликам, затем размечены просмотром контактных листов. Положительные —
только те, где пачка купюр видна однозначно; спорные исключены из обучения,
чтобы не учить модель на шуме.

Вывод из разметки: на 464x848 купюры РАЗЛИЧИМЫ на уровне патча (форма, полоса
бандероли, характерный цвет), хотя попиксельно неотличимы от столешницы.
Именно поэтому классификатор патчей работает там, где цветовой порог не смог.
"""

# Пачки купюр, видны однозначно
POSITIVE = [
    "X-43_0", "X-43_1", "X-43_2", "X-43_3",
    "X-44_0", "X-44_1", "X-44_2", "X-44_5",
    "X-45_0", "X-45_1", "X-45_2", "X-45_5",
    "X-3_2", "X-3_3", "X-3_4", "X-3_5",
    "X-13_5",
    "X-2_3",
    "X-10_0", "X-10_1", "X-10_2", "X-10_3", "X-10_4", "X-10_5",
]

# Спорные — НЕ используем ни как + ни как -
UNCERTAIN = ["X-45_3", "X-45_4", "X-2_1", "X-2_2", "X-19_0"]

# ИСПРАВЛЕНО. X-46_0..4 сначала были размечены как купюры: на вырезе объект
# выглядел как пачка с бандеролью. В контексте целого кадра видно, что это
# ВЫПЕЧКА на столе (тот самый ролик, где нарушение — еда на рабочем месте).
# Переведены в отрицательные. Ошибка нашлась только при проверке подсветки
# на полном кадре — вырез сам по себе вводил в заблуждение.


def split(index: list) -> tuple:
    """index — содержимое patches/index.json. Возвращает (pos, neg) списки id."""
    pos, neg = [], []
    for item in index:
        pid = item["id"]
        if pid in POSITIVE:
            pos.append(pid)
        elif pid in UNCERTAIN:
            continue
        else:
            neg.append(pid)
    return pos, neg
